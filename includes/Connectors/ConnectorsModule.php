<?php
/**
 * Registers the connectors that ship with the plugin.
 *
 * @package Estasoft\SyncEngine
 */

declare(strict_types=1);

namespace Estasoft\SyncEngine\Connectors;

defined( 'ABSPATH' ) || exit;

// phpcs:disable WordPress.Security.EscapeOutput.ExceptionNotEscaped -- the arguments of the exceptions here are error objects and fixed texts, not output.

use Estasoft\SyncEngine\Connectors\Odoo\OdooConnector;
use Estasoft\SyncEngine\Connectors\Support\AbstractApiConnector;
use Estasoft\SyncEngine\Connectors\Support\ConnectorDependencies;
use Estasoft\SyncEngine\Connectors\Support\ConnectorProvider;
use Estasoft\SyncEngine\Connectors\Support\Export\AbstractExportConnector;
use Estasoft\SyncEngine\Connectors\Support\Export\ExportService;
use Estasoft\SyncEngine\Connectors\Support\Export\ExportStore;
use Estasoft\SyncEngine\Connectors\Support\Export\RepositoryExportQueue;
use Estasoft\SyncEngine\Connectors\Support\GuardedConnector;
use Estasoft\SyncEngine\Connectors\Support\HostPins;
use Estasoft\SyncEngine\Connectors\Support\OAuth\OAuthResolver;
use Estasoft\SyncEngine\Connectors\Support\OAuth\OAuthTokenManager;
use Estasoft\SyncEngine\Connectors\Support\OAuth\RefreshTask;
use Estasoft\SyncEngine\Connectors\Support\OAuth\RepositoryTokenStorage;
use Estasoft\SyncEngine\Connectors\Support\OAuth\WpdbRefreshLock;
use Estasoft\SyncEngine\Connectors\Support\RequestPacer;
use Estasoft\SyncEngine\Container;
use Estasoft\SyncEngine\Contract\ConnectorInterface;
use Estasoft\SyncEngine\Contract\ConnectorRegistry;
use Estasoft\SyncEngine\Core\Queue\ObjectCacheRateStore;
use Estasoft\SyncEngine\Core\Queue\Scheduler;
use Estasoft\SyncEngine\Core\Services;
use Estasoft\SyncEngine\Domain\Connection;
use Estasoft\SyncEngine\ModuleInterface;

/**
 * Adds every connector listed in providers.php (generated by bin/generate-connector-index.php) to the estasoft_sync_register_connectors
 * filter, the same way a third-party connector plugin adds its own. Each one is registered as a Closure under its id, so a connector is built
 * the first time it is needed and a site with 36 connectors builds only the one it uses. The filter runs at priority 5, before the default 10,
 * so an add-on can replace a connector by registering one with the same id.
 *
 * Also wires what the connectors share: the API pacer, the OAuth token manager and its scheduled refresh, and the export store and service.
 */
final class ConnectorsModule implements ModuleInterface {

	/**
	 * Container key of the Odoo connector.
	 */
	public const ODOO = 'connectors.odoo';

	/**
	 * Container key of the shared services handed to every connector.
	 */
	public const DEPENDENCIES = 'connectors.dependencies';

	/**
	 * Container key of the OAuth token manager.
	 */
	public const TOKENS = 'connectors.oauth_tokens';

	/**
	 * Container key of the token storage.
	 */
	public const TOKEN_STORAGE = 'connectors.token_storage';

	/**
	 * Container key of the OAuth resolver.
	 */
	public const OAUTH_RESOLVER = 'connectors.oauth_resolver';

	/**
	 * Container key of the scheduled refresh task.
	 */
	public const REFRESH_TASK = 'connectors.refresh_task';

	/**
	 * Container key of the API pacer.
	 */
	public const PACER = 'connectors.pacer';

	/**
	 * Container key of the export file store.
	 */
	public const EXPORT_STORE = 'connectors.export_store';

	/**
	 * Container key of the export service.
	 */
	public const EXPORT_SERVICE = 'connectors.export_service';

	/**
	 * Container key of the refresh lock.
	 */
	public const LOCK = 'connectors.lock';

	/**
	 * Providers by connector id; null until read.
	 *
	 * @var array<string,class-string<ConnectorProvider>>|null
	 */
	private ?array $providers = null;

	/**
	 * Set up with what it depends on.
	 *
	 * @param array<string,class-string<ConnectorProvider>>|null $providers Providers by id; defaults to the generated providers.php.
	 */
	public function __construct( ?array $providers = null ) {
		$this->providers = $providers;
	}

	/**
	 * Register the shared services and the connectors as lazy services.
	 *
	 * @param Container $container Service container.
	 */
	public function services( Container $container ): void {
		$container->set(
			self::PACER,
			static fn( Container $c ): RequestPacer => new RequestPacer(
				wp_using_ext_object_cache() ? new ObjectCacheRateStore() : $c->get( Services::RATE_STATE_REPOSITORY ),
				$c->get( Services::CLOCK )
			)
		);
		$container->set(
			self::LOCK,
			static fn( Container $c ): WpdbRefreshLock => new WpdbRefreshLock( $c->get( Services::WPDB ), $c->get( Services::CLOCK ) )
		);
		$container->set(
			self::TOKEN_STORAGE,
			static fn( Container $c ): RepositoryTokenStorage => new RepositoryTokenStorage( $c->get( Services::CONNECTION_REPOSITORY ), $c->get( Services::PAUSE_CONTROLLER ) )
		);
		$container->set(
			self::OAUTH_RESOLVER,
			static fn( Container $c ): OAuthResolver => new OAuthResolver( static fn(): ConnectorRegistry => $c->get( Services::CONNECTOR_REGISTRY ) )
		);
		$container->set(
			self::TOKENS,
			static fn( Container $c ): OAuthTokenManager => new OAuthTokenManager(
				$c->get( Services::HTTP_CLIENT ),
				$c->get( Services::CLOCK ),
				$c->get( self::TOKEN_STORAGE ),
				$c->get( self::LOCK ),
				static fn( Connection $connection ) => $c->get( self::OAUTH_RESOLVER )->providerFor( $connection ),
				null,
				$c->get( Services::LOGGER )
			)
		);
		$container->set(
			self::REFRESH_TASK,
			static fn( Container $c ): RefreshTask => new RefreshTask( $c->get( self::TOKEN_STORAGE ), $c->get( self::TOKENS ), $c->get( self::OAUTH_RESOLVER ), $c->get( Services::LOGGER ), $c->get( Services::CLOCK ) )
		);
		$container->set(
			self::EXPORT_STORE,
			static fn( Container $c ): ExportStore => new ExportStore(
				static function (): string {
					$uploads = wp_upload_dir( null, false );
					return empty( $uploads['error'] ) && ! empty( $uploads['basedir'] ) ? (string) $uploads['basedir'] : '';
				},
				$c->get( Services::CLOCK )
			)
		);
		$container->set(
			self::EXPORT_SERVICE,
			static fn( Container $c ): ExportService => new ExportService(
				$c->get( self::EXPORT_STORE ),
				static function ( int $connectionId ) use ( $c ): ?AbstractExportConnector {
					$connection = $c->get( Services::CONNECTION_REPOSITORY )->findWithoutSecrets( $connectionId );
					$connector  = null === $connection ? null : $c->get( Services::CONNECTOR_REGISTRY )->get( $connection->connector );
					$connector  = $connector instanceof GuardedConnector ? $connector->inner() : $connector;
					return $connector instanceof AbstractExportConnector ? $connector : null;
				},
				new RepositoryExportQueue( $c->get( Services::QUEUE_REPOSITORY ) ),
				$c->get( self::LOCK ),
				$c->get( Services::LOGGER ),
				static fn( int $connectionId ) => $c->get( Services::CONNECTION_REPOSITORY )->findWithoutSecrets( $connectionId )
			)
		);
		$container->set(
			self::DEPENDENCIES,
			static fn( Container $c ): ConnectorDependencies => new ConnectorDependencies(
				$c->get( Services::HTTP_CLIENT ),
				$c->get( Services::CLOCK ),
				$c->get( self::TOKENS ),
				$c->get( self::EXPORT_STORE ),
				$c->get( Services::LOGGER ),
				$c->get( self::PACER )
			)
		);
		$container->set(
			self::ODOO,
			fn( Container $c ): ConnectorInterface => $this->make( $c, 'odoo' )
		);
	}

	/**
	 * Add the connectors to the registration filter, the refresh task to the scheduler, and the clean-up of old export files.
	 *
	 * @param Container $container Service container.
	 */
	public function hooks( Container $container ): void {
		add_filter(
			'estasoft_sync_register_connectors',
			function ( $connectors ) use ( $container ): array {
				$connectors = is_array( $connectors ) ? $connectors : array();
				foreach ( array_keys( $this->providers() ) as $id ) {
					$connectors[ $id ] = fn(): ConnectorInterface => 'odoo' === $id ? $container->get( self::ODOO ) : $this->make( $container, (string) $id );
				}
				return $connectors;
			},
			5
		);
		add_filter(
			'estasoft_sync_scheduled_tasks',
			static function ( $tasks ): array {
				$tasks                      = is_array( $tasks ) ? $tasks : array();
				$tasks[ RefreshTask::HOOK ] = RefreshTask::INTERVAL;
				return $tasks;
			}
		);
		add_filter(
			'estasoft_sync_option_names',
			static function ( $names ): array {
				$names   = is_array( $names ) ? $names : array();
				$names[] = WpdbRefreshLock::PREFIX . '*';
				return $names;
			}
		);
		// Connect to an address HostPolicy checked, not to whatever the name resolves to a moment later (cURL transport only).
		add_action( 'http_api_curl', array( HostPins::class, 'apply' ), 10, 3 );
		add_action(
			RefreshTask::HOOK,
			static function () use ( $container ): void {
				try {
					$container->get( self::REFRESH_TASK )->run();
				} catch ( \Throwable $error ) {
					unset( $error ); // A failed run is tried again in five minutes; the token manager already logged what it could.
				}
			}
		);
		add_action(
			Scheduler::HOOK_PRUNE,
			static function () use ( $container ): void {
				try {
					$container->get( self::EXPORT_SERVICE )->purgeExpired();
				} catch ( \Throwable $error ) {
					unset( $error ); // Old export files are removed again tomorrow.
				}
			}
		);
	}

	/**
	 * The providers by connector id.
	 *
	 * @return array<string,class-string<ConnectorProvider>>
	 */
	public function providers(): array {
		if ( null === $this->providers ) {
			$list            = require __DIR__ . '/providers.php';
			$this->providers = is_array( $list ) ? $list : array();
		}
		return $this->providers;
	}

	/**
	 * Build one connector through its provider.
	 *
	 * @param Container $container Service container.
	 * @param string    $id        Connector id.
	 *
	 * @throws \LogicException When no provider exists for the id.
	 */
	private function make( Container $container, string $id ): ConnectorInterface {
		$class = $this->providers()[ $id ] ?? null;
		if ( null === $class || ! is_subclass_of( $class, ConnectorProvider::class ) ) {
			throw new \LogicException( 'No provider for connector ' . $id . '.' );
		}
		$provider  = new $class();
		$connector = $provider->create( $container->get( self::DEPENDENCIES ) );
		return $connector instanceof AbstractApiConnector ? GuardedConnector::wrap( $connector, $container->get( self::TOKENS ) ) : $connector;
	}
}
