<?php
/**
 * Writes includes/Connectors/providers.php: the sorted list of connector providers.
 *
 *   php bin/generate-connector-index.php           write the file
 *   php bin/generate-connector-index.php --check   fail (exit 1) when the file is out of date, change nothing
 *   php bin/generate-connector-index.php --print   print what the file would contain
 *
 * It scans includes/Connectors/{Vendor}/{Name}Provider.php, loads each class, reads its id() and writes `id => Provider::class`. The output is
 * deterministic, so several people running it at once write the same file.
 *
 * @package Estasoft\SyncEngine
 */

declare(strict_types=1);

/**
 * Build the contents of providers.php for a plugin root.
 *
 * A provider that cannot be loaded (its connector is not written yet) is skipped and named in `$problems`; two providers with the same id, or an id
 * that is not lower case letters, digits and dashes, are errors.
 *
 * @param string             $root     Plugin root directory.
 * @param array<int,string>|null $problems Receives a line for every provider that was skipped.
 * @return string File contents.
 *
 * @throws RuntimeException When a provider has no valid id, or two providers share an id.
 */
function estasoft_generate_connector_index( string $root, ?array &$problems = null ): string {
	$problems = array();
	if ( ! defined( 'ABSPATH' ) ) {
		define( 'ABSPATH', sys_get_temp_dir() . '/estasoft-sync-abspath/' );
	}
	require_once $root . '/includes/Autoloader.php';
	Estasoft\SyncEngine\Autoloader::register( 'Estasoft\\SyncEngine\\', $root . '/includes/' );

	$map   = array();
	$files = glob( $root . '/includes/Connectors/*/*Provider.php' );
	sort( $files );
	foreach ( (array) $files as $file ) {
		$dir   = basename( dirname( $file ) );
		$name  = basename( $file, '.php' );
		$class = 'Estasoft\\SyncEngine\\Connectors\\' . $dir . '\\' . $name;
		if ( 'Support' === $dir ) {
			continue;
		}
		if ( ! class_exists( $class ) ) {
			$problems[] = "Cannot load {$class} from {$file}.";
			continue;
		}
		$reflection = new ReflectionClass( $class );
		if ( ! $reflection->implementsInterface( Estasoft\SyncEngine\Connectors\Support\ConnectorProvider::class ) || ! $reflection->isInstantiable() ) {
			continue;
		}
		try {
			$id = $reflection->newInstance()->id();
		} catch ( Throwable $error ) {
			$problems[] = "{$class} could not tell its id: " . $error->getMessage();
			continue;
		}
		if ( 1 !== preg_match( '/^[a-z][a-z0-9-]*$/', $id ) ) {
			throw new RuntimeException( "{$class}::id() must be lower case letters, digits and dashes, got '{$id}'." );
		}
		if ( isset( $map[ $id ] ) ) {
			throw new RuntimeException( "Connector id '{$id}' is used by {$map[$id]} and {$class}." );
		}
		$map[ $id ] = $class;
	}
	ksort( $map );

	$lines = '';
	$width = 0;
	foreach ( array_keys( $map ) as $id ) {
		$width = max( $width, strlen( (string) $id ) );
	}
	foreach ( $map as $id => $class ) {
		// Arrows are aligned, as the WordPress coding standard requires for multi-line arrays.
		$lines .= "\t'" . $id . "'" . str_repeat( ' ', $width - strlen( (string) $id ) ) . ' => \\' . $class . "::class,\n";
	}
	return <<<PHP
<?php
/**
 * The connector providers, by connector id. Generated by bin/generate-connector-index.php: do not edit by hand.
 *
 * @package Estasoft\\SyncEngine
 */

declare(strict_types=1);

defined( 'ABSPATH' ) || exit;

return array(
{$lines});

PHP;
}

if ( ! defined( 'ESTASOFT_INDEX_LIB' ) ) {
	$root   = dirname( __DIR__ );
	$target = $root . '/includes/Connectors/providers.php';
	$mode   = $argv[1] ?? '';
	try {
		$problems = array();
		$text     = estasoft_generate_connector_index( $root, $problems );
	} catch ( Throwable $error ) {
		fwrite( STDERR, 'generate-connector-index: ' . $error->getMessage() . "\n" );
		exit( 1 );
	}
	foreach ( $problems as $problem ) {
		fwrite( STDERR, 'generate-connector-index: skipped. ' . $problem . "\n" );
	}
	if ( '--print' === $mode ) {
		echo $text;
		exit( 0 );
	}
	$current = is_file( $target ) ? (string) file_get_contents( $target ) : '';
	if ( '--check' === $mode ) {
		if ( array() !== $problems ) {
			exit( 1 );
		}
		if ( $current !== $text ) {
			fwrite( STDERR, "includes/Connectors/providers.php is out of date. Run: php bin/generate-connector-index.php\n" );
			exit( 1 );
		}
		echo "providers.php is up to date.\n";
		exit( 0 );
	}
	if ( $current !== $text ) {
		$temporary = $target . '.' . getmypid() . '.tmp';
		file_put_contents( $temporary, $text );
		rename( $temporary, $target );
		echo "Wrote includes/Connectors/providers.php\n";
	} else {
		echo "providers.php already up to date.\n";
	}
}
